"""Exercise deterministic overlays, collisions and synced-copy refusals."""

import json
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

from house.core import CannotRunError
from house.sync import GITHUB_DEFAULTS, defaults, generated, merge, sync


@pytest.fixture
def configured(repo, write):
    write("config/clangd.toml", '[CompileFlags]\nAdd=["-Wall"]\nCompiler="clang++"\n')
    write(
        "config/devcontainer.json",
        '{"customizations":{"vscode":{"settings":{"clangd.arguments":["--background-index"]},"extensions":[]}}}\n',
    )
    repo.config["sync"]["files"] = [".clangd", ".devcontainer/devcontainer.json"]
    repo.config["sync"]["overlay"] = {
        "clangd": {"CompileFlags": {"Add": ["-Wextra", "-Wall"]}},
        "devcontainer": {
            "image": "sample",
            "customizations": {
                "vscode": {"settings": {"clangd.arguments": ["--clang-tidy"]}},
            },
        },
    }
    return repo


def test_overlay_preserves_base_and_is_byte_identical(configured):
    first = generated(configured)
    assert '"-Wall"' in first[".clangd"]
    assert '"-Wextra"' in first[".clangd"]
    assert first[".clangd"].count('"-Wall"') == 1
    settings = json.loads(first[".devcontainer/devcontainer.json"])["customizations"][
        "vscode"
    ]["settings"]
    assert settings["clangd.arguments"] == ["--background-index", "--clang-tidy"]
    sync(configured)
    assert generated(configured) == first
    assert sync(configured, check=True) == []
    assert all(
        (configured.root / name).read_text() == text for name, text in first.items()
    )


def test_scalar_conflict_requires_declared_replacement(configured):
    configured.config["sync"]["overlay"]["clangd"]["CompileFlags"]["Compiler"] = (
        "other++"
    )
    with pytest.raises(
        CannotRunError,
        match=r"scalar conflict at CompileFlags\.Compiler",
    ):
        generated(configured)
    configured.config["sync"]["replace"] = {"clangd": ["CompileFlags.Compiler"]}
    assert "other++" in generated(configured)[".clangd"]


@pytest.mark.parametrize(
    ("file_id", "overlay", "message"),
    [
        ("unknown", {}, "unsupported overlay file id"),
        ("clangd", {"Unknown": {}}, "unsupported key Unknown"),
        (
            "clangd",
            {"CompileFlags": {"Unknown": []}},
            "unsupported key CompileFlags.Unknown",
        ),
        (
            "clangd",
            {"CompileFlags": {"Add": "bad"}},
            "unsupported type for CompileFlags.Add",
        ),
    ],
)
def test_unsupported_overlay_has_specific_diagnostic(
    configured,
    file_id,
    overlay,
    message,
):
    configured.config["sync"]["overlay"] = {file_id: overlay}
    with pytest.raises(CannotRunError, match=message):
        generated(configured)


def test_copy_files_refuse_overlays_and_ruff_is_repo_owned(repo, write):
    write("config/.editorconfig", "# Generated by dev.py sync.\nroot = true\n")
    repo.config["sync"]["files"] = [".editorconfig"]
    assert generated(repo)[".editorconfig"].startswith("# Generated")
    repo.config["sync"]["overlay"] = {"editorconfig": {"root": False}}
    with pytest.raises(CannotRunError, match="unsupported overlay file id"):
        generated(repo)
    repo.config["sync"]["overlay"] = {}
    repo.config["sync"]["files"] = ["ruff.toml"]
    with pytest.raises(CannotRunError, match="unsupported synced file"):
        generated(repo)


def test_missing_or_unreadable_base_is_unavailable(configured):
    (configured.root / "config/clangd.toml").write_bytes(b"\xff")
    with pytest.raises(CannotRunError, match="cannot read"):
        generated(configured)


def test_recursive_map_merge_and_list_order():
    base = {"a": {"values": ["one"], "enabled": True}}
    overlay = {"a": {"values": ["two", "one", "two"]}}
    assert merge(base, overlay, "sample") == {
        "a": {"values": ["one", "two"], "enabled": True},
    }
    assert base == {"a": {"values": ["one"], "enabled": True}}


def test_invalid_structured_values_and_replacement_keys(configured):
    configured.config["sync"]["overlay"]["clangd"]["CompileFlags"]["Add"] = [99]
    with pytest.raises(
        CannotRunError,
        match=r"unsupported value type at CompileFlags\.Add",
    ):
        generated(configured)
    configured.config["sync"]["overlay"]["clangd"]["CompileFlags"]["Add"] = ["-Wall"]
    configured.config["sync"]["replace"] = {"clangd": ["CompileFlags.Unknown"]}
    with pytest.raises(CannotRunError, match="unsupported replacement keys"):
        generated(configured)


def test_profile_overlay_uses_the_same_merge_rules(configured, monkeypatch):
    module = "synthetic_sync_profile"
    profile = SimpleNamespace(
        enabled=True,
        sync_overlay={
            "clangd": {"CompileFlags": {"Add": ["-Wconversion"]}},
        },
    )
    monkeypatch.setitem(sys.modules, module, SimpleNamespace(profile=profile))
    configured.config["trees"] = [{"name": "extra", "profile": module + ":profile"}]
    assert "-Wconversion" in generated(configured)[".clangd"]
    profile.enabled = False
    assert "-Wconversion" not in generated(configured)[".clangd"]


def test_devcontainer_requires_an_environment(configured):
    configured.config["sync"]["overlay"]["devcontainer"].pop("image")
    with pytest.raises(CannotRunError, match="devcontainer: requires build or image"):
        generated(configured)
    configured.config["sync"]["overlay"]["devcontainer"]["build"] = {
        "dockerfile": "Dockerfile",
    }
    assert json.loads(generated(configured)[".devcontainer/devcontainer.json"])[
        "build"
    ] == {"dockerfile": "Dockerfile"}


def test_github_files_are_synced_with_a_marker_for_their_syntax(repo, write):
    write("config/github/config.yml", "blank_issues_enabled: false\n")
    write("config/github/defect.yml", "name: Defect\n")
    write("config/github/pull_request_template.md", "## Gates\n")
    repo.config["sync"]["files"] = list(GITHUB_DEFAULTS)
    output = generated(repo)
    assert output[".github/ISSUE_TEMPLATE/config.yml"] == (
        "# Generated by dev.py sync.\nblank_issues_enabled: false\n"
    )
    assert output[".github/ISSUE_TEMPLATE/defect.yml"] == (
        "# Generated by dev.py sync.\nname: Defect\n"
    )
    assert output[".github/pull_request_template.md"] == (
        "<!-- Generated by dev.py sync. -->\n## Gates\n"
    )
    assert sync(repo) == []
    assert sync(repo, check=True) == []
    (repo.root / ".github/pull_request_template.md").write_text("edited\n")
    assert sync(repo, check=True) == [".github/pull_request_template.md"]


